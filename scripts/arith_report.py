"""Collect arithmetic-grid runs into a Markdown report.

    .venv/bin/python scripts/arith_report.py --runs results/toy/grid --out docs/results-arith-grid.md

Reads each run directory's config.json, log.jsonl and per_example.npz (written by
looptf.toy.train) and writes:
  1. one row per run: unique core blocks, training loops, params, seed, depths mastered;
  2. the grid (unique core blocks x loops): highest depth mastered and test accuracy,
     mean over seeds (min-max in brackets);
  3. final test accuracy by depth for every run, at its training loop count;
  4. looped runs scored at other loop counts (does adding loops at test time help?);
  5. accuracy by answer length, to separate "too many steps" from "numbers too big".
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def load_run(d: Path) -> dict | None:
    cfg_p, log_p = d / "config.json", d / "log.jsonl"
    if not cfg_p.exists() or not log_p.exists():
        return None
    cfg = json.loads(cfg_p.read_text())
    a = cfg["args"]
    lo, _, hi = a["train_loops"].partition("-")
    lo, hi = int(lo), int(hi or lo)
    evals, mastered, last_step = [], {}, 0
    for line in log_p.read_text().splitlines():
        r = json.loads(line)
        if "eval" in r:
            evals.append(r)
        if "mastered_depth" in r:
            mastered[int(r["mastered_depth"])] = r["step"]
        last_step = max(last_step, r.get("step", 0))
    pe = d / "per_example.npz"
    return {
        "name": d.name, "core": a["n_core"], "loops": (lo, hi), "seed": a["seed"], "lr": a["lr"],
        "params": cfg["params"], "steps": a["steps"], "last_step": last_step,
        "finished": pe.exists(), "mastered": mastered,
        "final_eval": {int(k): {int(dd): v for dd, v in row.items()} for k, row in evals[-1]["eval"].items()}
        if evals else {},
        "per_example": dict(np.load(pe)) if pe.exists() else None,
    }


def loops_label(r) -> str:
    lo, hi = r["loops"]
    return f"{hi}" if lo == hi else f"{lo}-{hi} (random)"


def max_mastered(r) -> int:
    return max(r["mastered"], default=0)


def fmt_range(vals, fmt="{:.2f}") -> str:
    if not vals:
        return "–"
    m = sum(vals) / len(vals)
    if len(vals) == 1:
        return fmt.format(m)
    return f"{fmt.format(m)} ({fmt.format(min(vals))}–{fmt.format(max(vals))})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="results/toy/grid")
    ap.add_argument("--out", default="docs/results-arith-grid.md")
    ap.add_argument("--title", default="Arithmetic grid: unique blocks × loops")
    a = ap.parse_args()
    runs_dir = Path(a.runs) if Path(a.runs).is_absolute() else ROOT / a.runs
    runs = [r for d in sorted(runs_dir.iterdir()) if d.is_dir() and (r := load_run(d))]
    runs.sort(key=lambda r: (r["loops"][0] != r["loops"][1], r["core"], r["loops"][1], r["seed"]))
    depths = sorted({dd for r in runs for row in r["final_eval"].values() for dd in row})
    L = []
    w = L.append
    w(f"# {a.title}\n")
    src = runs_dir.relative_to(ROOT) if runs_dir.is_relative_to(ROOT) else runs_dir
    w(f"Source: `{src}`, {len(runs)} runs "
      f"({sum(r['finished'] for r in runs)} finished). Generated by `scripts/arith_report.py`.\n")
    w("Every model has 1 prelude block + *core* blocks run *loops* times + 1 coda block, width 256. "
      "Trained on depths 1–8 with a curriculum (add a depth at 90% exact match on the current top "
      "depth); tested on held-out problems at depths 1–16. Accuracy = exact match on the whole "
      "answer (chance ≈ 0). Effective depth = core × loops.\n")

    # 1. runs
    w("## 1. Runs\n")
    w("| run | core | loops | eff. depth | params | lr | seed | steps | deepest mastered | steps to master depth 2 / 3 / 4 / 6 / 8 |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for r in runs:
        eff = r["core"] * r["loops"][1]
        ms = " / ".join(str(r["mastered"].get(dd, "–")) for dd in (2, 3, 4, 6, 8))
        w(f"| {r['name']} | {r['core']} | {loops_label(r)} | {eff} | {r['params']/1e6:.1f}M | {r['lr']:g} | "
          f"{r['seed']} | {r['last_step']}{'' if r['finished'] else ' (running)'} | {max_mastered(r)} | {ms} |")
    w("")

    # 2. grid
    fixed = [r for r in runs if r["loops"][0] == r["loops"][1]]
    cores = sorted({r["core"] for r in fixed})
    ks = sorted({r["loops"][1] for r in fixed})
    by_cell = defaultdict(list)
    for r in fixed:
        by_cell[(r["core"], r["loops"][1])].append(r)
    for letter, (title, fn, fmt) in zip("abc", [
        ("Deepest depth mastered (mean over seeds, min–max)", max_mastered, "{:.1f}"),
        ("Test accuracy, depths 3–8 (trained range, unseen problems)",
         lambda r: np.mean([r["final_eval"][r["loops"][1]].get(dd, np.nan) for dd in range(3, 9)]), "{:.2f}"),
        ("Test accuracy, depths 9–16 (deeper than training)",
         lambda r: np.mean([r["final_eval"][r["loops"][1]].get(dd, np.nan) for dd in range(9, 17)]), "{:.2f}"),
    ]):
        w(f"## 2{letter}. Grid: {title}\n")
        w("Rows: unique core blocks. Columns: loops. Cells on the same anti-diagonal have the same effective depth (compute).\n")
        w("| core \\ loops | " + " | ".join(f"×{k}" for k in ks) + " |")
        w("|---|" + "---|" * len(ks))
        for c in cores:
            cells = []
            for k in ks:
                rs = [r for r in by_cell.get((c, k), []) if r["final_eval"]]
                vals = [float(fn(r)) for r in rs]
                vals = [v for v in vals if not np.isnan(v)]
                cells.append(f"{fmt_range(vals, fmt)} [eff {c*k}]" if rs else "")
            w(f"| {c} | " + " | ".join(cells) + " |")
        w("")

    # 3. per-depth accuracy
    w("## 3. Test accuracy by depth (at each run's training loop count)\n")
    w("Depths 1–2 are scored on held-out problems never seen in training (20% of the distinct problems at those depths were held out).\n")
    w("| run | " + " | ".join(str(dd) for dd in depths) + " |")
    w("|---|" + "---|" * len(depths))
    for r in runs:
        k = r["loops"][1]
        row = r["final_eval"].get(k, {})
        w(f"| {r['name']} | " + " | ".join(f"{row[dd]:.2f}" if dd in row else "" for dd in depths) + " |")
    w("")

    # 4. test-time loops
    w("## 4. Looped runs at other loop counts (test time)\n")
    w("Does running more loops than in training help on deeper problems? Mean accuracy over depth bands.\n")
    w("| run | K at test | depths 1–2 | 3–8 | 9–12 | 13–16 |")
    w("|---|---|---|---|---|---|")
    for r in runs:
        if r["loops"][1] == 1:
            continue
        for k, row in sorted(r["final_eval"].items()):
            band = lambda lo, hi: np.nanmean([row.get(dd, np.nan) for dd in range(lo, hi + 1)])
            w(f"| {r['name']} | {k} | {band(1, 2):.2f} | {band(3, 8):.2f} | {band(9, 12):.2f} | {band(13, 16):.2f} |")
    w("")

    # 5. answer length
    w("## 5. Accuracy by answer length (depths 3–8, at training loop count)\n")
    w("If accuracy falls with answer length at a fixed depth, number size (not step count) is a bottleneck.\n")
    buckets = [(1, 2), (3, 4), (5, 6), (7, 12)]
    w("| run | " + " | ".join(f"{lo}–{hi} digits" for lo, hi in buckets) + " |")
    w("|---|" + "---|" * len(buckets))
    for r in runs:
        pe = r["per_example"]
        if pe is None:
            continue
        k = r["loops"][1]
        m = (pe["K"] == k) & (pe["depth"] >= 3) & (pe["depth"] <= 8)
        ndig = pe["n_tgt"] - 1 - (pe["answer"] < 0)
        cells = []
        for lo, hi in buckets:
            mm = m & (ndig >= lo) & (ndig <= hi)
            cells.append(f"{pe['correct'][mm].mean():.2f} (n={mm.sum()})" if mm.sum() else "–")
        w(f"| {r['name']} | " + " | ".join(cells) + " |")
    w("")

    # 6. depth x answer-size matrix (and input size), when the data has these labels
    if any(r["per_example"] is not None and "ans_digits" in r["per_example"] for r in runs):
        w("## 6. Where each model breaks: accuracy by depth × answer digits\n")
        w("At each run's training loop count. Cells are exact-match accuracy (± 95% interval half-width); "
          "blank = no test problems of that kind. Input digits = 1 unless stated.\n")
        for r in runs:
            pe = r["per_example"]
            if pe is None or "ans_digits" not in pe:
                continue
            k = r["loops"][1]
            base = (pe["K"] == k)
            if "op_digits" in pe:
                base = base & (pe["op_digits"] == 1)
            ads = sorted(set(pe["ans_digits"][base].tolist()))
            w(f"### {r['name']}\n")
            w("| depth \\ answer digits | " + " | ".join(str(x) for x in ads) + " | all |")
            w("|---|" + "---|" * (len(ads) + 1))
            for dd in sorted(set(pe["depth"][base].tolist())):
                cells = []
                for x in ads + [None]:
                    m = base & (pe["depth"] == dd) & ((pe["ans_digits"] == x) if x is not None else True)
                    n = int(m.sum())
                    if n < 20:
                        cells.append("")
                        continue
                    pr = float(pe["correct"][m].mean())
                    cells.append(f"{pr:.2f}±{1.96 * (pr * (1 - pr) / n) ** 0.5:.2f}")
                w(f"| {dd} | " + " | ".join(cells) + " |")
            w("")
            if "op_digits" in pe:
                mm = (pe["K"] == k) & (pe["op_digits"] > 1)
                if mm.sum():
                    w(f"Multi-digit inputs ({r['name']}): depth × input digits × answer digits\n")
                    w("| depth | input digits | " + " | ".join(f"{x}-digit ans" for x in range(1, 8)) + " |")
                    w("|---|---|" + "---|" * 7)
                    for dd in sorted(set(pe["depth"][mm].tolist())):
                        for od in sorted(set(pe["op_digits"][mm & (pe["depth"] == dd)].tolist())):
                            cells = []
                            for x in range(1, 8):
                                m = mm & (pe["depth"] == dd) & (pe["op_digits"] == od) & (pe["ans_digits"] == x)
                                n = int(m.sum())
                                cells.append(f"{pe['correct'][m].mean():.2f}" if n >= 20 else "")
                            w(f"| {dd} | {od} | " + " | ".join(cells) + " |")
                    w("")

    out = Path(a.out) if Path(a.out).is_absolute() else ROOT / a.out
    out.write_text("\n".join(L))
    print(f"wrote {out} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
