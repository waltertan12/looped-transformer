#!/usr/bin/env python
"""H18 / D-014 report: do the tag fixes let models handle longer numbers?

    scripts/tags_report.py --score     # score checkpoints on data/longnum_* (GPU, 2 at a time is the caller's job)
    scripts/tags_report.py             # print tables + verdicts, write docs/results-tags.md

Runs compared (40k steps, seed 0, normal order): tags/<m>-offset, tags/<m>-sep, place/<m>-normal-pv
(tags, no fix) and bal/<m>-normal (no tags), for m in c2k1 (shallow), c2k8 (looped).
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from eval_ckpt import load_checkpoint, train_k  # noqa: E402
from looptf.toy.data import decode, encode  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
VARIANTS = {"offset": "tags/{m}-offset-s0", "sep": "tags/{m}-sep-s0", "tags": "place/{m}-normal-pv-s0",
            "none": "bal/{m}-normal-s0"}
MODELS = {"shallow": ("c2k1", 1), "looped": ("c2k8", 8)}
SETS = ("longnum_add", "longnum_mul")


def h18_verdict(exact4: float, within5: float, inrange_deltas: list[float]) -> str:
    """D-014 rule on the looped model: pass if 4-digit a+b exact >= 0.5 and trained sizes lose <= 0.03."""
    if exact4 >= 0.5:
        return "pass" if all(d >= -0.03 for d in inrange_deltas) else "fail: hurts trained sizes"
    return "approximate only" if within5 >= 0.8 else "fail"


@torch.no_grad()
def greedy(model, k: int, prompt: str, maxn: int = 12) -> str:
    x, out = encode(prompt), ""
    for _ in range(maxn):
        with torch.autocast("cuda", dtype=torch.bfloat16):
            lg = model(torch.tensor([x], device="cuda"), n_loops=k)
        t = int(lg[0, -1].argmax())
        x.append(t)
        c = decode([t])
        if c == "#":
            break
        out += c
    return out


def within5(run: str, n: int = 300, digits: int = 4) -> float:
    model, args = load_checkpoint(REPO / f"checkpoints/toy/{run}.pt", "cuda")
    k, rng, ok = train_k(args), np.random.default_rng(0), 0
    for _ in range(n):
        a, b = (int(v) for v in rng.integers(10 ** (digits - 1), 10 ** digits, 2))
        o = greedy(model, k, f"{a}+{b}=")
        if args.get("reverse_answer"):
            o = o[0] + o[1:][::-1] if o.startswith("-") else o[::-1]
        try:
            ok += abs(int(o) - (a + b)) <= 0.05 * (a + b)
        except ValueError:
            pass
    return ok / n


def score_all() -> None:
    for mname, (tag, _) in MODELS.items():
        for v, pat in VARIANTS.items():
            run = pat.format(m=tag)
            for ds in SETS:
                out = REPO / f"results/toy/longnum/{run.replace('/', '_')}-{ds}/per_example.npz"
                if out.exists():
                    continue
                subprocess.run([sys.executable, str(REPO / "scripts/eval_ckpt.py"), "--ckpt", f"checkpoints/toy/{run}.pt",
                                "--data", f"data/{ds}", "--out", str(out), "--mem_fraction", "0.3"], check=True)


def _ops(run: str, ds: str) -> dict:
    return dict(np.load(REPO / f"results/toy/longnum/{run.replace('/', '_')}-{ds}/per_example.npz"))


def inrange(run: str, K: int) -> tuple[float, float]:
    """(multi-digit inputs depths 1–3, big answers 3–5 digits on 1-digit inputs depths 2–6) exact."""
    d = np.load(REPO / f"results/toy/{run}/per_example.npz")
    k = d["K"] == K
    a = d["correct"][k & (d["op_digits"] >= 2) & (d["depth"] <= 3)].mean()
    b = d["correct"][k & (d["op_digits"] == 1) & (d["ans_digits"] >= 3) & (d["ans_digits"] <= 5)
                     & (d["depth"] >= 2) & (d["depth"] <= 6)].mean()
    return float(a), float(b)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--score", action="store_true")
    ap.add_argument("--out", default="docs/results-tags.md")
    a = ap.parse_args()
    if a.score:
        score_all()
        return
    L = ["# H18 results: tag fixes for longer numbers (D-014)", "",
         "40k steps, seed 0, normal order. Exact accuracy unless noted. Training had inputs up to 3 digits.",
         "Generated by `scripts/tags_report.py`.", ""]
    verdicts = {}
    for mname, (tag, K) in MODELS.items():
        L += [f"## {mname}", "", "| tags | add d1: 3-digit | 4-digit | 5-digit | add d2: 4-digit | mul d1: 3-digit | 4-digit "
              "| 4-digit a+b within 5% | trained sizes: multi-digit inputs | big answers |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        base = inrange(VARIANTS["tags"].format(m=tag), K)
        for v, pat in VARIANTS.items():
            run = pat.format(m=tag)
            add, mul = _ops(run, "longnum_add"), _ops(run, "longnum_mul")
            acc = lambda d, dep, k: float(d["correct"][(d["depth"] == dep) & (d["in_digits"] == k)].mean())  # noqa: E731
            w5 = within5(run)
            ir = inrange(run, K)
            L.append(f"| {v} | {acc(add, 1, 3):.2f} | {acc(add, 1, 4):.2f} | {acc(add, 1, 5):.2f} | {acc(add, 2, 4):.2f} "
                     f"| {acc(mul, 1, 3):.2f} | {acc(mul, 1, 4):.2f} | {w5:.2f} | {ir[0]:.2f} | {ir[1]:.2f} |")
            if mname == "looped" and v in ("offset", "sep"):
                verdicts[v] = h18_verdict(acc(add, 1, 4), w5, [ir[0] - base[0], ir[1] - base[1]])
        L.append("")
    L += ["## Verdicts (looped, D-014 rule)", ""]
    L += [f"- **{v}**: {r}" for v, r in verdicts.items()]
    L += ["", "Rule: pass if 4-digit `a+b` exact ≥ 0.5 and trained-size accuracy within 0.03 of tags without a fix.",
          "Also reported against ≥ 0.7 (as good as in-range 3-digit sums with tags)."]
    out = REPO / a.out
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
